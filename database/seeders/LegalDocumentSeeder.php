<?php

declare(strict_types=1);

namespace Database\Seeders;

use App\Models\LegalDocument;
use Illuminate\Database\Seeder;

class LegalDocumentSeeder extends Seeder
{
    public function run(): void
    {
        $this->publishIfMissing(
            LegalDocument::TYPE_OFERTA,
            'Публичная оферта',
            <<<'TEXT'
1. Общие положения
Настоящая публичная оферта (далее — «Оферта») определяет условия использования сервиса Smart Planogram Control Center (далее — «Сервис»). Акцептом Оферты является регистрация в Сервисе и/или оплата выбранного тарифа.

2. Предмет
Исполнитель предоставляет Заказчику доступ к облачному сервису управления планограммами на условиях выбранного тарифа.

3. Порядок оплаты
Оплата производится банковским переводом по выставленному счёту. Доступ к платным функциям предоставляется после подтверждения оплаты.

4. Ответственность
Сервис предоставляется «как есть». Исполнитель не несёт ответственность за косвенные убытки Заказчика. Совокупная ответственность ограничена суммой, уплаченной Заказчиком за текущий период подписки.

5. Персональные данные
Обработка персональных данных осуществляется в соответствии с Политикой конфиденциальности.

6. Срок действия
Оферта действует бессрочно до её отзыва Исполнителем. Актуальная редакция публикуется по адресу /oferta.
TEXT
        );

        $this->publishIfMissing(
            LegalDocument::TYPE_PRIVACY,
            'Политика конфиденциальности',
            <<<'TEXT'
1. Какие данные мы собираем
Мы обрабатываем учётные данные пользователей (имя, email, телефон), данные организаций-арендаторов и технические журналы входов.

2. Цели обработки
Данные используются для предоставления Сервиса, биллинга, поддержки, обеспечения безопасности и исполнения требований законодательства.

3. Хранение
Данные хранятся на серверах Исполнителя в течение срока договора и установленного законом срока хранения.

4. Передача третьим лицам
Данные не продаются. Передача возможна только подрядчикам, обеспечивающим работу Сервиса, либо по требованию уполномоченных органов.

5. Права субъекта
Пользователь вправе запросить доступ, исправление или удаление своих данных, направив обращение на email администратора.

6. Контакты
По вопросам обработки персональных данных обращайтесь к администратору Сервиса.
TEXT
        );
    }

    private function publishIfMissing(string $type, string $title, string $content): void
    {
        $exists = LegalDocument::query()->where('type', $type)->exists();

        if ($exists) {
            return;
        }

        LegalDocument::query()->create([
            'type' => $type,
            'title' => $title,
            'content' => trim($content),
            'version' => 1,
            'is_active' => true,
        ]);
    }
}
